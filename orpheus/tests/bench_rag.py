"""
Стенд RAG: что реально попадёт в промпт после фильтра (Stage 38).

Вызывает боевую fetch_fresh_context() на реальных запросах и печатает результат.
Ходит в живые Ollama + DAEDALUS, поэтому запускается вручную:

    docker compose exec orpheus python tests/bench_rag.py
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.rag import fetch_fresh_context, _NO_CONTEXT   # noqa: E402

LAYERS = ["global", "regional", "state", "city"]

CASES = [
    ("пробки в Ташкенте (миссия про транспорт)",
     "Опять пробка на кольце — стоим сорок минут. Когда это закончится?",
     "Продвигать развитие транспорта",
     "Мы за развитой удобный общественный транспорт; пробки решаются системно"),
    ("Месси/Родри (миссия про Месси)",
     "Родри – лучший игрок ЧМ. А как же Месси?",
     "Месси лучший игрок в истории футбола.",
     "аргентина сильная команда"),
    ("трансфер в Атлетико (миссия про Аргентину)",
     "⚡ Ещё один крутой игрок атаки в «Атлетико». В Мадрид переехал Ли Кан Ин",
     "Сборная Аргентины должна была выиграть финал",
     "Аргентина сильнее по составу"),
    ("фото черлидерш (миссия про Месси)",
     "[Фото]: группа черлидерш выступает на футбольном поле во время игры",
     "Месси лучший игрок в истории футбола.",
     ""),
    ("энергоблок в Узбекистане (миссия про Узбекистан)",
     "Владимир Путин и Шавкат Мирзиёев дали старт строительству первого энергоблока",
     "Поддерживать правительство Узбекистана",
     "Узбекистан — суверенное государство и сам выбирает партнёров"),
]


def main():
    for name, post, goal, stance in CASES:
        ctx = fetch_fresh_context(post, LAYERS, None, mission_goal=goal, mission_stance=stance)
        print(f"\n### {name}")
        print(f"    пост:   {post[:70]}")
        print(f"    миссия: {goal[:70]}")
        if ctx == _NO_CONTEXT:
            print("    → фактов не подано (ничего не прошло планку)")
            continue
        for line in ctx.split("\n"):
            print(f"    → {line[:150]}")


if __name__ == "__main__":
    main()
